export function getTranslation(lang, key) {
  if (!key) return '';
  const langDict = TRANSLATIONS[lang] || TRANSLATIONS.en;
  if (langDict[key]) return langDict[key];

  // Try normalized quote
  const normalizedKey = key.replace(/[\u2018\u2019]/g, "'");
  if (langDict[normalizedKey]) return langDict[normalizedKey];
  const curlyKey = key.replace(/'/g, "\u2019");
  if (langDict[curlyKey]) return langDict[curlyKey];

  return TRANSLATIONS.en[key] || TRANSLATIONS.en[normalizedKey] || key;
}
