async function seed() {
  console.log('[Seed Care Records] Seeding comprehensive medical history records into MySQL...');
  try {
    for (const r of COMPREHENSIVE_CARE_RECORDS) {
      await query(
        `INSERT INTO care_records 
          (record_id, resident_id, date, time, blood_pressure, temperature, weight, observation, notes, recorded_by, record_type, created_at)
         VALUES (?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?)
         ON DUPLICATE KEY UPDATE
          date = VALUES(date),
          time = VALUES(time),
          blood_pressure = VALUES(blood_pressure),
          temperature = VALUES(temperature),
          weight = VALUES(weight),
          observation = VALUES(observation),
          notes = VALUES(notes),
          recorded_by = VALUES(recorded_by),
          record_type = VALUES(record_type),
          created_at = VALUES(created_at)`,
        [
          r.record_id,
          r.resident_id,
          r.date,
          r.time,
          r.blood_pressure,
          r.temperature,
          r.weight,
          r.observation,
          r.notes,
          r.recorded_by,
          r.record_type,
          r.created_at
        ]
      );
    }

    const counts = await query(
      'SELECT resident_id, COUNT(*) as count FROM care_records GROUP BY resident_id ORDER BY resident_id'
    );
    console.log('Successfully seeded care records in MySQL:', counts);
  } catch (err) {
    console.error('Error seeding care records:', err);
  } finally {
    process.exit(0);
  }
}

seed();
